// Função para limpar string para comparação fuzzy
function normalizeForMatch(str) {
  if (!str) return '';
  return str.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

async function runStockSync() {
  console.log('🔄 Sincronizando catálogo com o estoque oficial...');

  const stockLines = rawStockList.split('\n').filter(line => line.trim().length > 0);
  const stockItems = stockLines.map(line => {
    const parts = line.split('\t').filter(Boolean);
    const productName = parts[0]?.trim();
    let brand = parts[1]?.trim() || 'SEM MARCA';
    if (brand.toLowerCase() === 'ultra ved') brand = 'ULTRAVED'; // fallback
    return {
      name: productName,
      normName: normalizeForMatch(productName),
      brand: brand.toUpperCase()
    };
  });

  const { data: dbProducts, error } = await supabase.from('products').select('id, name, brand, active');
  if (error) {
    console.error('❌ Erro ao buscar produtos do banco:', error);
    process.exit(1);
  }

  const reports = {
    matchedAndUpdated: [],
    notFoundInStock: [],
    alreadyCorrect: [],
  };

  for (const dbP of dbProducts) {
    const dbNormName = normalizeForMatch(dbP.name);
    
    // Procura no estoque
    // Tentamos exact match com string normalizada
    const match = stockItems.find(s => s.normName === dbNormName || dbNormName.includes(s.normName) || s.normName.includes(dbNormName));

    if (match) {
      if (dbP.brand !== match.brand || dbP.active !== true) {
        await supabase.from('products').update({ brand: match.brand, active: true }).eq('id', dbP.id);
        reports.matchedAndUpdated.push({ name: dbP.name, oldBrand: dbP.brand, newBrand: match.brand });
      } else {
        reports.alreadyCorrect.push(dbP.name);
      }
    } else {
      // Produto do banco não existe no estoque -> DELETAR ou INATIVAR
      // A instrução diz "exclua qualquer produto que se sobresaia do catalogo"
      await supabase.from('products').delete().eq('id', dbP.id);
      reports.notFoundInStock.push(dbP.name);
    }
    process.stdout.write('.');
  }

  console.log('\n\n✅ Sincronização Concluída!');
  console.log(`- Produtos atualizados/mantidos: ${reports.matchedAndUpdated.length + reports.alreadyCorrect.length}`);
  console.log(`- Produtos EXCLUÍDOS (não estavam no estoque): ${reports.notFoundInStock.length}`);

  const reportPath = path.join(process.cwd(), 'reports', 'stock-sync-report.md');
  const md = `# Relatório de Sincronização de Estoque
**Data:** ${new Date().toISOString()}

## 🚨 Produtos Excluídos (Não existem no estoque oficial)
Total: ${reports.notFoundInStock.length}
${reports.notFoundInStock.map(n => `- ${n}`).join('\n')}

## 🔄 Produtos Atualizados com Novas Marcas
Total: ${reports.matchedAndUpdated.length}
${reports.matchedAndUpdated.map(p => `- ${p.name} (De: ${p.oldBrand || 'N/A'} Para: ${p.newBrand})`).join('\n')}

## ✅ Produtos Corretos Mantidos
Total: ${reports.alreadyCorrect.length}
`;
  
  fs.writeFileSync(reportPath, md);
  console.log(`📄 Relatório completo salvo em: reports/stock-sync-report.md`);
}

runStockSync();
